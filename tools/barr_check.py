#!/usr/bin/env python3
"""Check C sources against the automatable BARR-C:2018 rules.

Usage:
    python tools/barr_check.py [--format] [PATH ...]

PATH may be a file or a folder (searched recursively for .c and .h files);
the default is the current folder. --format also runs clang-format with the
project's .clang-format and reports files that are not formatted.

Rules that need human judgement are listed in docs/coding_standard.md.
Exit status: 0 when no findings, 1 when there are findings.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys

MAX_LINE_WIDTH = 80
END_OF_FILE_COMMENT = "/*** end of file ***/"
SKIP_DIRECTORIES = {".git", "build", "third_party", "templates"}
GENERATED_MARKERS = ("autogenerated", "auto-generated", "do not edit")
FILE_NAME_PATTERN = re.compile(r"^[a-z0-9_]+\.[ch]$")
FORBIDDEN_TOKENS = [
    ("1.7.a", re.compile(r"\bauto\b"), "keyword 'auto'"),
    ("1.7.b", re.compile(r"\bregister\b"), "keyword 'register'"),
    ("1.7.c", re.compile(r"\bgoto\b"), "keyword 'goto' (avoid)"),
    ("1.7.d", re.compile(r"\bcontinue\b"), "keyword 'continue' (avoid)"),
    ("5.2.b", re.compile(r"\bshort\b"), "keyword 'short'"),
    ("5.2.b", re.compile(r"\blong\b"), "keyword 'long'"),
    ("8.5.b", re.compile(r"\b(abort|exit|setjmp|longjmp)\s*\("),
     "forbidden library call"),
]


def find_sources(paths):
    """Yield every .c and .h file under the given paths."""
    for path in paths:
        if os.path.isfile(path):
            yield path
            continue
        for root, directories, files in os.walk(path):
            directories[:] = [name for name in directories
                              if name not in SKIP_DIRECTORIES]
            for name in sorted(files):
                if name.endswith((".c", ".h")):
                    yield os.path.join(root, name)


def is_generated(text):
    """Return True if the file header says the file is generated."""
    head = text[:400].lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def split_code_and_comments(text):
    """Return (code, comments) where each is a list of (line, text) parts.

    String and character literals are blanked in the code so that keywords
    inside them are not reported.
    """
    code = []
    comments = []
    state = "code"
    line = 1
    buffer = []
    comment_start = 1
    index = 0
    length = len(text)
    while index < length:
        char = text[index]
        pair = text[index:index + 2]
        if state == "code":
            if pair == "/*":
                state, comment_start, buffer = "block", line, []
                index += 2
                continue
            if pair == "//":
                state, comment_start, buffer = "line", line, []
                index += 2
                continue
            if char in "\"'":
                state = char
            code.append((line, char))
        elif state == "block":
            if pair == "*/":
                comments.append((comment_start, "".join(buffer)))
                state = "code"
                index += 2
                continue
            buffer.append(char)
        elif state == "line":
            if char == "\n":
                comments.append((comment_start, "".join(buffer)))
                state = "code"
                code.append((line, char))
            else:
                buffer.append(char)
        else:
            if char == "\\":
                if text[index + 1:index + 2] == "\n":
                    line += 1
                index += 2
                continue
            if char == state:
                state = "code"
            elif char == "\n":
                state = "code"
            code.append((line, " " if char not in "\n\"'" else char))
        if char == "\n":
            line += 1
        index += 1
    if state in ("block", "line"):
        comments.append((comment_start, "".join(buffer)))
    return code, comments


def code_lines(code):
    """Join (line, char) pairs back into a dict of line -> code text."""
    lines = {}
    for number, char in code:
        lines[number] = lines.get(number, "") + char
    return lines


def check_text(path, raw, findings):
    """Run all per-file checks and append (path, line, rule, text)."""
    name = os.path.basename(path)

    def report(line, rule, message):
        findings.append((path, line, rule, message))

    if FILE_NAME_PATTERN.match(name) is None:
        report(1, "4.1.a", "file name must use only a-z, 0-9 and '_'")

    if b"\r" in raw:
        report(raw[:raw.index(b"\r")].count(b"\n") + 1, "3.6.a",
               "CR-LF line ending (use LF only)")
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        report(1, "3.6.b", "file is not valid UTF-8")
        return

    for number, line in enumerate(text.replace("\r", "").split("\n"), 1):
        if "\t" in line:
            report(number, "3.5.a", "tab character")
        if len(line) > MAX_LINE_WIDTH:
            report(number, "1.2.a",
                   "line is %d characters (max %d)"
                   % (len(line), MAX_LINE_WIDTH))
        for char in line:
            if (ord(char) < 0x20 and char not in "\t\f") or ord(char) == 0x7F:
                report(number, "3.6.b", "non-printing character")
                break

    stripped = text.rstrip("\n").split("\n")
    last_line = stripped[-1].strip() if stripped else ""
    if last_line != END_OF_FILE_COMMENT or not text.endswith("\n"):
        report(len(stripped), "3.3.c",
               "file must end with '%s' and a newline" % END_OF_FILE_COMMENT)

    code, comments = split_code_and_comments(text)
    for number, comment in comments:
        body = comment.replace("*/", "")
        if "/*" in body or "//" in body or "\\" in body:
            report(number, "2.1.b", "comment contains /*, // or a backslash")

    lines = code_lines(code)
    for number in sorted(lines):
        line = lines[number]
        if line.lstrip().startswith("#"):
            continue
        for rule, pattern, message in FORBIDDEN_TOKENS:
            if pattern.search(line):
                report(number, rule, message)

    # Directives come from the raw text, because the code view blanks the
    # quoted file names of #include lines.
    raw_lines = text.replace("\r", "").split("\n")
    directives = [raw_lines[number - 1].strip() for number in sorted(lines)
                  if lines[number].lstrip().startswith("#")]
    if name.endswith(".h"):
        guard_ok = (len(directives) >= 2
                    and directives[0].startswith("#ifndef")
                    and directives[1].startswith("#define")
                    and directives[0].split()[1:2] == directives[1].split()[1:2])
        if not guard_ok:
            report(1, "4.2.b", "header must start with an #ifndef/#define guard")
    else:
        header = name[:-2] + ".h"
        if not os.path.isfile(os.path.join(os.path.dirname(path), header)):
            report(1, "4.2.a", "no header file named %s" % header)
        include = re.compile(r'#\s*include\s+"([^"]*/)?%s"' % re.escape(header))
        if not any(include.match(line) for line in directives):
            report(1, "4.3.c", "source file must #include \"%s\"" % header)


def find_clang_format():
    """Locate clang-format on PATH or inside the VS Code C/C++ extension."""
    found = shutil.which("clang-format")
    if found:
        return found
    extensions = os.path.join(os.path.expanduser("~"), ".vscode", "extensions")
    if os.path.isdir(extensions):
        for folder in sorted(os.listdir(extensions), reverse=True):
            if folder.startswith("ms-vscode.cpptools-"):
                candidate = os.path.join(extensions, folder, "LLVM", "bin",
                                         "clang-format.exe")
                if os.path.isfile(candidate):
                    return candidate
    return None


def check_format(paths, findings):
    """Report files that clang-format would change."""
    clang_format = find_clang_format()
    if clang_format is None:
        print("note: clang-format not found; format check skipped")
        return
    for path in paths:
        result = subprocess.run(
            [clang_format, "--style=file", "--dry-run", "--Werror", path],
            capture_output=True, text=True, check=False)
        if result.returncode != 0:
            findings.append((path, 1, "format",
                             "not formatted; run clang-format -i %s" % path))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("paths", nargs="*", default=["."])
    parser.add_argument("--format", action="store_true",
                        help="also check formatting with clang-format")
    arguments = parser.parse_args()

    findings = []
    checked = []
    for path in find_sources(arguments.paths):
        with open(path, "rb") as source:
            raw = source.read()
        if is_generated(raw.decode("utf-8", "replace")):
            continue
        checked.append(path)
        check_text(path, raw, findings)
    if arguments.format:
        check_format(checked, findings)

    for path, line, rule, message in findings:
        print("%s:%d: [BARR-C %s] %s" % (path, line, rule, message))
    print("%d file(s) checked, %d finding(s)" % (len(checked), len(findings)))
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
